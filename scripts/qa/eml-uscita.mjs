// Prova: nel nodo EML la X e Esc riportano a Columbus; la scheda "columbus-rack-eml" porta nell'EML (niente simulazione-copia).
import puppeteer from 'puppeteer-core'
const BASE = process.argv[2] ?? 'http://localhost:5190'
const attendi = (ms) => new Promise((r) => setTimeout(r, ms))
const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--use-angle=swiftshader', '--enable-unsafe-swiftshader', '--ignore-gpu-blocklist', '--mute-audio'] })
const p = await b.newPage()
await p.setViewport({ width: 1280, height: 720 })
await p.goto(BASE + '/', { waitUntil: 'networkidle2' })
await p.waitForFunction(() => window.__app)
await p.evaluate(() => window.__app.avvia())
await p.waitForFunction(() => window.__iss, { timeout: 60000 })
await attendi(4000)
const nodo = () => p.evaluate(() => window.__iss.st.current.nodoId)
await p.evaluate(() => window.__iss.saltaA('columbus')); await attendi(3000)
await p.evaluate(() => window.__iss.apriScheda('columbus-rack-eml')); await attendi(1500)
await p.evaluate(() => [...document.querySelectorAll('button')].find((x) => /Entra nell'EML/.test(x.textContent))?.click())
await attendi(7000)
console.log('dopo scheda ->', await nodo())
await p.keyboard.press('Escape'); await attendi(5000)
console.log('dopo Esc ->', await nodo())
await p.evaluate(() => window.__iss.saltaA('eml')); await attendi(5000)
await p.evaluate(() => [...document.querySelectorAll('button')].find((x) => /Avvia esperimento/.test(x.textContent))?.click()); await attendi(1500)
await p.keyboard.press('Escape'); await attendi(1500)
console.log('Esc con passi aperti ->', await nodo(), '(deve restare eml)')
await p.evaluate(() => [...document.querySelectorAll('button')].find((x) => /Esci/.test(x.textContent))?.click()); await attendi(5000)
console.log('dopo X ->', await nodo())
await b.close()
