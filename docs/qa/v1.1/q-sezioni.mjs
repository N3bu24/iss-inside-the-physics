import puppeteer from 'puppeteer-core'
const attendi = (ms) => new Promise((r) => setTimeout(r, ms))
const b = await puppeteer.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: 'new', args: ['--use-angle=swiftshader','--enable-unsafe-swiftshader','--ignore-gpu-blocklist','--mute-audio'] })
const p = await b.newPage(); await p.setViewport({ width: 1440, height: 900 })
await p.goto('http://localhost:5173/', { waitUntil: 'networkidle2' })
await p.waitForFunction(() => window.__app); await p.evaluate(() => window.__app.avvia())
await p.waitForFunction(() => window.__iss, { timeout: 60000 }); await attendi(3000)
await p.evaluate(() => window.__iss.apriSimulazione('aurora')); await attendi(6000)
const stato = () => p.evaluate(() => ({ passo: /PASSO \d/i.test(document.body.innerText), tabs: [...document.querySelectorAll('[role=tab]')].map(t=>t.textContent+':'+t.getAttribute('aria-selected')) }))
console.log('prima', JSON.stringify(await stato()))
await p.evaluate(() => [...document.querySelectorAll('[role=tab]')].find(t=>/Terra/.test(t.textContent))?.click()); await attendi(4000)
console.log('dopo clic sezione', JSON.stringify(await stato()))
await p.screenshot({ path: 'docs/qa/v1.1/aurora-terra-1440x900.png' })
await p.evaluate(() => [...document.querySelectorAll('[role=tab]')].find(t=>/Particella/.test(t.textContent))?.click()); await attendi(2500)
console.log('ritorno', JSON.stringify(await stato()))
await b.close()
